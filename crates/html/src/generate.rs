//! The code generator: compiled templates become a values struct and a render function
//! each, written as plain, reviewable Rust.

use alloc::string::String;
use alloc::vec::Vec;
use core::fmt::{self, Write as _};

use crate::compile::{Part, Template};
use crate::names;

/// Writes Rust source for `templates`: for each one a values struct with one
/// `&dyn sibuna_html::Value` field per distinct placeholder (in order of first
/// appearance) and a `render_<stem>` function that writes the literal runs and the
/// escaped values into any `core::fmt::Write` sink without allocating.
///
/// The output holds items only (no inner attributes), so a crate includes it with
/// `include!(concat!(env!("OUT_DIR"), "/snippets.rs"))`, and it names this crate as
/// `::sibuna_html`, so the including crate depends on `sibuna-html` under that name. It is
/// ASCII: other characters in literals are written as `\u{..}` escapes. Two templates
/// with the same stem produce duplicate items, which rustc reports.
pub fn generate(templates: &[Template]) -> String {
    let mut code = String::new();
    // Writing into a `String` cannot fail.
    let _ = write_all(&mut code, templates);
    code
}

fn write_all(code: &mut String, templates: &[Template]) -> fmt::Result {
    code.push_str("// Generated by sibuna-html. Edit the snippets, not this file.\n");
    for template in templates {
        code.push('\n');
        write_struct(code, template)?;
        code.push('\n');
        write_function(code, template)?;
    }
    Ok(())
}

fn write_struct(code: &mut String, template: &Template) -> fmt::Result {
    let file = template.file_name();
    let name = template.struct_name();
    if template.field_count() == 0 {
        writeln!(code, "/// The snippet `{file}` has no placeholders.")?;
        writeln!(code, "#[derive(Clone, Copy, Debug, Default)]")?;
        return writeln!(code, "pub struct {name};");
    }
    writeln!(code, "/// Values for the snippet `{file}`, borrowed for one render.")?;
    writeln!(code, "#[derive(Clone, Copy)]")?;
    if template.field_names().any(|field| field.bytes().any(|byte| byte.is_ascii_uppercase())) {
        writeln!(code, "#[allow(non_snake_case)]")?;
    }
    writeln!(code, "pub struct {name}<'a> {{")?;
    for field in template.field_names() {
        writeln!(code, "    /// Fills `{{{{ {field} }}}}`.")?;
        let identifier = names::field_identifier(field);
        writeln!(code, "    pub {identifier}: &'a dyn ::sibuna_html::Value,")?;
    }
    writeln!(code, "}}")
}

/// Generated functions longer than this many lines carry allowances for clippy's
/// `too_many_lines` and the workspace limit checker: they are straight-line code, one
/// statement per run or value, and splitting them would only obscure the snippet.
const LONG_FUNCTION: usize = 60;

/// The most escaped characters in one generated string literal, so generated lines stay
/// within 99 columns.
const LITERAL_WIDTH: usize = 80;

fn write_function(code: &mut String, template: &Template) -> fmt::Result {
    let file = template.file_name();
    let lifetime = if template.field_count() == 0 { "" } else { "<'_>" };
    let values = if template.placeholder_count() == 0 { "_values" } else { "values" };
    let mut body = String::new();
    write_body(&mut body, template)?;
    writeln!(code, "/// Renders the snippet `{file}` into `out`, escaping every value.")?;
    writeln!(code, "///")?;
    writeln!(code, "/// Fails only when `out` fails; the partial output must then be discarded.")?;
    if body.lines().count() > LONG_FUNCTION {
        writeln!(code, "// xtask: allow-long-function generated snippet renderer")?;
        writeln!(code, "#[allow(clippy::too_many_lines)]")?;
    }
    writeln!(code, "pub fn {}(", template.function_name())?;
    writeln!(code, "    out: &mut impl ::core::fmt::Write,")?;
    writeln!(code, "    {values}: &{}{lifetime},", template.struct_name())?;
    writeln!(code, ") -> ::core::fmt::Result {{")?;
    code.push_str(&body);
    writeln!(code, "    Ok(())")?;
    writeln!(code, "}}")
}

/// Writes one statement per literal run and per placeholder.
fn write_body(code: &mut String, template: &Template) -> fmt::Result {
    let fields: Vec<&str> = template.field_names().collect();
    for part in template.parts() {
        match part {
            Part::Literal(range) => {
                let text = template.source().get(range.clone()).unwrap_or_default();
                write_literal(code, text)?;
            }
            Part::Slot { field, .. } => {
                let name = fields.get(*field).copied().unwrap_or_default();
                let identifier = names::field_identifier(name);
                writeln!(code, "    ::sibuna_html::write_value(out, values.{identifier})?;")?;
            }
        }
    }
    Ok(())
}

/// Writes one `out.write_str(..)` call. Longer text becomes a `concat!` with one string
/// per source line, and long lines are cut into pieces of at most 80 escaped characters,
/// so the generated code reads like the snippet.
fn write_literal(code: &mut String, text: &str) -> fmt::Result {
    let mut pieces: Vec<&str> = Vec::new();
    for line in text.split_inclusive('\n') {
        push_pieces(&mut pieces, line);
    }
    if let [piece] = pieces.as_slice() {
        // `    out.write_str("` and `")?;` take 23 of the 99 columns.
        if piece.chars().map(escaped_width).sum::<usize>() <= 99 - 23 {
            code.push_str("    out.write_str(");
            write_string(code, piece)?;
            return code.write_str(")?;\n");
        }
        code.push_str("    out.write_str(\n        ");
        write_string(code, piece)?;
        return code.write_str(",\n    )?;\n");
    }
    code.push_str("    out.write_str(concat!(\n");
    for piece in pieces {
        code.push_str("        ");
        write_string(code, piece)?;
        code.push_str(",\n");
    }
    code.write_str("    ))?;\n")
}

/// Cuts `line` at character boundaries into pieces whose escaped form fits
/// `LITERAL_WIDTH`.
fn push_pieces<'a>(pieces: &mut Vec<&'a str>, line: &'a str) {
    let mut start = 0;
    let mut width = 0;
    for (index, character) in line.char_indices() {
        let escaped = escaped_width(character);
        if width + escaped > LITERAL_WIDTH && index > start {
            pieces.push(line.get(start..index).unwrap_or_default());
            start = index;
            width = 0;
        }
        width += escaped;
    }
    if start < line.len() {
        pieces.push(line.get(start..).unwrap_or_default());
    }
}

/// Returns how many characters `write_string` writes for `character`.
fn escaped_width(character: char) -> usize {
    match character {
        '"' | '\\' | '\n' | '\r' | '\t' => 2,
        ' '..='~' => 1,
        // `\u{`, the hexadecimal digits, `}`.
        other => {
            let bits = 32 - u32::from(other).leading_zeros();
            4 + usize::try_from(bits.div_ceil(4).max(1)).unwrap_or(8)
        }
    }
}

/// Writes `text` as an ASCII Rust string literal.
fn write_string(code: &mut String, text: &str) -> fmt::Result {
    code.push('"');
    for character in text.chars() {
        match character {
            '"' => code.push_str("\\\""),
            '\\' => code.push_str("\\\\"),
            '\n' => code.push_str("\\n"),
            '\r' => code.push_str("\\r"),
            '\t' => code.push_str("\\t"),
            ' '..='~' => code.push(character),
            other => write!(code, "\\u{{{:x}}}", u32::from(other))?,
        }
    }
    code.write_char('"')
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;
    use crate::compile;

    #[test]
    fn generated_code_is_readable_rust() {
        let source = "<p>{{ type }}</p>\n<i>{{ Name }}{{ type }}</i>";
        let template = compile("snippets/field-row.html", source).unwrap();
        let expected = r#"// Generated by sibuna-html. Edit the snippets, not this file.

/// Values for the snippet `field-row.html`, borrowed for one render.
#[derive(Clone, Copy)]
#[allow(non_snake_case)]
pub struct FieldRowValues<'a> {
    /// Fills `{{ type }}`.
    pub r#type: &'a dyn ::sibuna_html::Value,
    /// Fills `{{ Name }}`.
    pub Name: &'a dyn ::sibuna_html::Value,
}

/// Renders the snippet `field-row.html` into `out`, escaping every value.
///
/// Fails only when `out` fails; the partial output must then be discarded.
pub fn render_field_row(
    out: &mut impl ::core::fmt::Write,
    values: &FieldRowValues<'_>,
) -> ::core::fmt::Result {
    out.write_str("<p>")?;
    ::sibuna_html::write_value(out, values.r#type)?;
    out.write_str(concat!(
        "</p>\n",
        "<i>",
    ))?;
    ::sibuna_html::write_value(out, values.Name)?;
    ::sibuna_html::write_value(out, values.r#type)?;
    out.write_str("</i>")?;
    Ok(())
}
"#;
        assert_eq!(generate(&[template]), expected);
    }

    #[test]
    fn snippets_without_placeholders_get_a_unit_struct() {
        let code = generate(&[compile("plain.html", "<hr>").unwrap()]);
        assert!(code.contains("pub struct PlainValues;\n"));
        assert!(code.contains("    _values: &PlainValues,\n"));
    }

    #[test]
    fn literals_escape_quotes_backslashes_controls_and_non_ascii() {
        let mut code = String::new();
        write_string(&mut code, "a\"b\\c\r\t\0\u{7f}\u{e9}\u{4e16}~").unwrap();
        assert_eq!(code, r#""a\"b\\c\r\t\u{0}\u{7f}\u{e9}\u{4e16}~""#);
        let width: usize = "a\"b\\c\r\t\0\u{7f}\u{e9}\u{4e16}~".chars().map(escaped_width).sum();
        assert_eq!(width, code.len() - 2);
    }

    #[test]
    fn long_lines_are_cut_into_pieces_at_character_boundaries() {
        let line = "\u{e9}".repeat(30) + &"x".repeat(100) + "\n";
        let mut pieces = Vec::new();
        push_pieces(&mut pieces, &line);
        assert_eq!(pieces.concat(), line);
        for piece in &pieces {
            assert!(piece.chars().map(escaped_width).sum::<usize>() <= LITERAL_WIDTH);
        }
        let mut code = String::new();
        write_literal(&mut code, &line).unwrap();
        assert!(code.lines().all(|generated| generated.len() <= 99));
        assert_eq!(code.matches("\",\n").count(), pieces.len());
    }
}
