//! The result document and the Markdown summary of `bench product`.

use super::{CaseResult, Options, Sample, WorkloadResult, wrk};
use crate::anubis;
use crate::daemon::IMPLEMENTATION;
use crate::json::Json;
use crate::report::{Table, fmt_count};
use crate::{meta, paths};

/// A figure of the side-by-side table: its name and how to write it for one workload.
type Figure<'f> = (&'static str, &'f dyn Fn(&WorkloadResult) -> String);

/// Returns the result document: the setup, every case and the limitations.
pub fn product_document(options: &Options, origin: &str, cases: &[CaseResult]) -> Json {
    let mut daemons = Json::object().with(IMPLEMENTATION, meta::binary(&options.daemon));
    if let Some(path) = &options.anubis {
        daemons.set("anubis", meta::binary(path));
    }
    let load = Json::object()
        .with("threads", options.load.threads)
        .with("connections", options.load.connections)
        .with("seconds", options.load.seconds)
        .with("repetitions", options.repetitions);
    let mut limitations: Vec<Json> = LIMITATIONS.iter().map(|&l| Json::from(l)).collect();
    let mut document = Json::object()
        .with("meta", meta::machine(&paths::workspace_root(), &options.cpus))
        .with("load", load)
        .with("wrk", wrk::version())
        .with("origin", origin);
    if let Some(path) = &options.anubis {
        document.set("anubis_version", anubis::version(path));
        limitations.extend(COMPARISON_LIMITATIONS.iter().map(|&l| Json::from(l)));
    }
    document
        .with("daemon_cpus", options.cpus.to_list())
        .with("load_cpus", options.load_cpus.to_list())
        .with("daemons", daemons)
        .with("runs", cases.iter().map(CaseResult::to_json).collect::<Vec<_>>())
        .with("limitations", limitations)
}

/// What these runs do not show, recorded with every result.
const LIMITATIONS: [&str; 6] = [
    "One host, loopback; wrk and the origin run on the load CPU set, the daemon on its own set.",
    "wrk is a closed-loop generator: its latency percentiles suffer coordinated omission under \
     saturation. `bench latency` measures latency at equal offered load instead.",
    "CPU time is user+system time of the daemon process from /proc/<pid>/stat (10 ms ticks), \
     read before and after each run; the origin's CPU is not included.",
    "Peak RSS is VmHWM after resetting it through /proc/<pid>/clear_refs before each run.",
    "Hashcash at 8 bits with a session solved once per case; browser solve time is not measured.",
    "No TLS, no WAN, no real browsers; a ranking on this host is not a ranking on yours.",
];

/// What a comparison with Anubis adds to [`LIMITATIONS`].
const COMPARISON_LIMITATIONS: [&str; 5] = [
    "Anubis runs with GOMAXPROCS equal to the Sibuna worker count, pinned to the same CPU set; \
     its policy challenges every Mozilla User-Agent, with DNSBL and the honeypot disabled.",
    "Hashcash work matched at 8 zero bits for Sibuna and 2 zero hex digits for Anubis. Anubis \
     signs sessions with its default Ed25519 key, Sibuna with its keyed BLAKE3 MAC.",
    "In forward-auth mode Anubis is asked at its check endpoint for the admitted and \
     challenged workloads; the static and attack workloads reach its default answer, as in \
     tools.py.",
    "Anubis is the official release binary, outside this repository; its origin transport runs \
     with Go's default idle-connection limits (no flags were changed).",
    "Every run starts after fewer than 3,000 sockets remain in TIME_WAIT; a workload whose \
     load generator could not connect is recorded as failed with the error text.",
];

/// Returns the Markdown summary: one table per mode, then, with Anubis, one side-by-side
/// table per mode.
pub fn product_markdown(options: &Options, cases: &[CaseResult]) -> String {
    let (title, command) = match &options.anubis {
        Some(_) => ("Sibuna and Anubis as whole products", "product --anubis"),
        None => ("Whole-product runs", "product"),
    };
    let mut out = format!(
        "# {title}\n\nGenerated by `cargo xtask bench {command}` on {}. wrk {} threads, \
         {} connections, {} s x {} repetitions (median, with the min-max of req/s beside \
         it); daemon CPUs {}, load CPUs {}.\n",
        meta::utc_now(),
        options.load.threads,
        options.load.connections,
        options.load.seconds,
        options.repetitions,
        options.cpus.to_list(),
        options.load_cpus.to_list()
    );
    for mode in &options.modes {
        let mut table = Table::new(&[
            "Product",
            "Workload",
            "Status",
            "req/s",
            "req/s min-max",
            "p50 us",
            "p90 us",
            "p99 us",
            "CPU us/req",
            "Peak RSS KiB",
        ]);
        for case in cases.iter().filter(|c| c.mode == *mode) {
            for w in &case.workloads {
                table.row(markdown_row(case, w));
            }
        }
        out.push_str(&format!("\n## {}\n\n{}", mode.name(), table.markdown()));
    }
    if options.anubis.is_some() {
        for mode in &options.modes {
            let mode_cases: Vec<&CaseResult> = cases.iter().filter(|c| c.mode == *mode).collect();
            out.push_str(&format!("\n## Side by side, {}\n\n", mode.name()));
            out.push_str("Medians; the status of each workload is in brackets.\n\n");
            out.push_str(&side_by_side(&mode_cases).markdown());
        }
    }
    out
}

fn markdown_row(case: &CaseResult, w: &WorkloadResult) -> Vec<String> {
    let rate = w.spread(Sample::requests_per_second);
    vec![
        case.subject.product().to_owned(),
        w.workload.name.to_owned(),
        status_text(w),
        rate.map_or_else(|| "failed".to_owned(), |s| fmt_count(s.median)),
        rate.map_or_else(
            || "-".to_owned(),
            |s| format!("{}-{}", fmt_count(s.min), fmt_count(s.max)),
        ),
        median_text(w, &|s| s.summary.latency.p50, 0),
        median_text(w, &|s| s.summary.latency.p90, 0),
        median_text(w, &|s| s.summary.latency.p99, 0),
        median_text(w, &Sample::cpu_us_per_request, 2),
        peak_rss_text(w),
    ]
}

fn status_text(w: &WorkloadResult) -> String {
    w.status.as_ref().map_or_else(|_| "failed".to_owned(), u16::to_string)
}

/// Returns the median of `value` over the samples of `w` with `decimals` decimals, or `-`.
fn median_text(w: &WorkloadResult, value: &dyn Fn(&Sample) -> f64, decimals: usize) -> String {
    w.spread(value).map_or_else(|| "-".to_owned(), |s| format!("{:.decimals$}", s.median))
}

fn peak_rss_text(w: &WorkloadResult) -> String {
    let peak = w.samples.iter().map(|s| s.peak_rss_kib).max();
    peak.map_or_else(|| "-".to_owned(), |k| k.to_string())
}

/// Returns one table of one mode with a column per product and, per workload, a row for
/// each figure: req/s (status), p99, CPU per request and peak resident memory.
fn side_by_side(cases: &[&CaseResult]) -> Table {
    let mut header = vec!["Workload", "Figure"];
    header.extend(cases.iter().map(|c| c.subject.product()));
    let mut table = Table::new(&header);
    let Some(first) = cases.first() else { return table };
    for (index, workload) in first.workloads.iter().enumerate() {
        let figures: [Figure<'_>; 4] = [
            ("req/s", &|w| {
                let rate = w.spread(Sample::requests_per_second);
                let rate = rate.map_or_else(|| "failed".to_owned(), |s| fmt_count(s.median));
                format!("{rate} ({})", status_text(w))
            }),
            ("p99 us", &|w| median_text(w, &|s| s.summary.latency.p99, 0)),
            ("CPU us/req", &|w| median_text(w, &Sample::cpu_us_per_request, 2)),
            ("Peak RSS KiB", &peak_rss_text),
        ];
        for (figure, text) in figures {
            let mut row = vec![workload.workload.name.to_owned(), figure.to_owned()];
            for case in cases {
                row.push(case.workloads.get(index).map_or_else(|| "-".to_owned(), text));
            }
            table.row(row);
        }
    }
    table
}
